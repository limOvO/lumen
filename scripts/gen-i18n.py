#!/usr/bin/env python3
"""Build src/js/core/i18n-data.js from scripts/i18n/keys.json + en.json.

- zh-Hant strings are the source (keys).
- zh-Hans is produced with OpenCC (t2s) so it stays in sync automatically.
- en comes from en.json (hand written).
Run after changing UI copy: python3 scripts/gen-i18n.py
"""
import json, subprocess, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
keys = json.loads((root / 'scripts/i18n/keys.json').read_text(encoding='utf-8'))
en = json.loads((root / 'scripts/i18n/en.json').read_text(encoding='utf-8'))

# two composed error templates cannot be extracted verbatim; provide patterns
extra = {
    '讀取檔案失敗：${rest}': ('读取文件失败：${rest}', 'Could not read file: ${rest}'),
    '寫入檔案失敗：${rest}': ('写入文件失败：${rest}', 'Could not write file: ${rest}'),
}
drop = {'讀取檔案失敗：${baseName(path)}${msg ?', '寫入檔案失敗：${baseName(path)}${msg ?'}

keys = [k for k in keys if k not in drop]
missing = [k for k in keys if k not in en]
if missing:
    sys.exit('missing English translations:\n  ' + '\n  '.join(missing))

def hans(s):
    out = subprocess.run(['opencc', '-c', 't2s.json'], input=s, capture_output=True, text=True)
    return out.stdout.rstrip('\n') if out.returncode == 0 else s

hans_map = {k: hans(k) for k in keys}
hans_map.update({k: v[0] for k, v in extra.items()})
en_map = {k: en[k] for k in keys}
en_map.update({k: v[1] for k, v in extra.items()})

def js(obj):
    lines = []
    for k, v in obj.items():
        lines.append('  %s: %s,' % (json.dumps(k, ensure_ascii=False), json.dumps(v, ensure_ascii=False)))
    return '{\n' + '\n'.join(lines) + '\n}'

out = """// AUTO-GENERATED by scripts/gen-i18n.py — do not edit by hand.
// Source language is Traditional Chinese (zh-Hant); keys are the exact UI copy.
export const TRANSLATIONS = {
  'zh-Hans': %s,
  en: %s,
};
""" % (js(hans_map), js(en_map))

target = root / 'src/js/core/i18n-data.js'
target.write_text(out, encoding='utf-8')
print('wrote', target, '(%d keys)' % len(hans_map))
