#!/usr/bin/env python3
"""Generate egui-app/src/i18n_data.rs from the shared JSON dictionaries.

Keys are the Traditional Chinese source strings; the same generated data is used
by the web frontend (via gen-i18n.py) so both UIs stay in sync.
"""
import json, pathlib, subprocess, sys

root = pathlib.Path(__file__).resolve().parent.parent
keys = json.loads((root / 'scripts/i18n/keys.json').read_text(encoding='utf-8'))
en = json.loads((root / 'scripts/i18n/en.json').read_text(encoding='utf-8'))
drop = {'讀取檔案失敗：${baseName(path)}${msg ?', '寫入檔案失敗：${baseName(path)}${msg ?'}
keys = [k for k in keys if k not in drop]

def hans(s):
    out = subprocess.run(['opencc', '-c', 't2s.json'], input=s, capture_output=True, text=True)
    return out.stdout.rstrip('\n') if out.returncode == 0 else s

rows_zhhans = [(k, hans(k)) for k in keys]
rows_en = [(k, en[k]) for k in keys]

def table(name, rows):
    lines = [f'pub static {name}: &[(&str, &str)] = &[']
    for k, v in rows:
        ek = k.replace('\\', '\\\\').replace('"', '\\"')
        ev = v.replace('\\', '\\\\').replace('"', '\\"')
        lines.append(f'    ("{ek}", "{ev}"),')
    lines.append('];')
    return '\n'.join(lines)

out = '// AUTO-GENERATED by scripts/gen-i18n-rs.py — do not edit by hand.\n\n'
out += table('ZH_HANS', rows_zhhans) + '\n\n' + table('EN', rows_en) + '\n'
target = root / 'egui-app/src/i18n_data.rs'
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(out, encoding='utf-8')
print('wrote', target, f'({len(keys)} strings)')
