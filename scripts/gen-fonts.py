#!/usr/bin/env python3
"""Build the subset CJK fonts used by the egui app.

Includes every character that appears in the shared i18n dictionaries (plus
printable ASCII and common CJK punctuation), so the egui build does not need to
load the 19 MB system Noto collection at runtime.

Needs fontTools:  python3 -m venv .cache/venv && .cache/venv/bin/pip install fonttools
Then:             .cache/venv/bin/python scripts/gen-fonts.py
"""
import json, pathlib, subprocess, sys

root = pathlib.Path(__file__).resolve().parent.parent
keys = json.loads((root / 'scripts/i18n/keys.json').read_text(encoding='utf-8'))
en = json.loads((root / 'scripts/i18n/en.json').read_text(encoding='utf-8'))
# Hans strings are generated by OpenCC, so their glyphs must be in the subset too
# (otherwise simplified Chinese renders as tofu in the egui build).
hans = []
for k in keys:
    out = subprocess.run(['opencc', '-c', 't2s.json'], input=k, capture_output=True, text=True)
    hans.append(out.stdout.rstrip('\n'))
chars = set(''.join(keys) + ''.join(en.values()) + ''.join(hans))
chars |= set(chr(c) for c in range(0x20, 0x7F))
chars |= set('·×—…「」『』（）：；，。、！？％／')
(root / 'scripts/i18n/subset-chars.txt').write_text(''.join(sorted(chars)), encoding='utf-8')

sources = {
    'NotoSansCJK-Regular.ttc': 'NotoSansCJK',
    'NotoSansCJK-Bold.ttc': 'NotoSansCJKBold',
}
for filename in sources:
    if not pathlib.Path('/usr/share/fonts/noto-cjk', filename).exists():
        sys.exit('system Noto Sans CJK collection not found: ' + filename)
outdir = root / 'egui-app/assets'
outdir.mkdir(parents=True, exist_ok=True)
faces = [
    ('NotoSansCJK-Regular.ttc', 'NotoSansCJKtc-subset.otf', 3),
    ('NotoSansCJK-Regular.ttc', 'NotoSansCJKsc-subset.otf', 2),
    ('NotoSansCJK-Bold.ttc', 'NotoSansCJKtc-Bold-subset.otf', 3),
    ('NotoSansCJK-Bold.ttc', 'NotoSansCJKsc-Bold-subset.otf', 2),
]
for source, name, index in faces:
    out = outdir / name
    subprocess.run(
        [sys.executable, '-m', 'fontTools.subset', '/usr/share/fonts/noto-cjk/' + source,
         f'--font-number={index}',
         f'--text-file={root}/scripts/i18n/subset-chars.txt',
         '--layout-features=*', '--no-hinting', '--desubroutinize',
         f'--output-file={out}'],
        check=True,
    )
    print(name, out.stat().st_size, 'bytes')

# ---------------------------------------------------------------------------
# Wide fallback faces: every hanzi encodable in GB2312/GBK/Big5. The small
# subsets above cover the UI; these cover arbitrary typed annotation text and
# file names (the egui build used to show tofu for chars outside the UI set).
# ---------------------------------------------------------------------------
def common_cjk_chars():
    """Every hanzi encodable in GB2312/GBK/Big5.

    GBK/Big5 trail bytes start at 0x40 (not 0xA1), so both halves must be
    scanned or common characters such as 專 silently miss the fallback face.
    """
    chars = set()
    for enc in ("gb2312",):
        for b1 in range(0xA1, 0xFF):
            for b2 in range(0xA1, 0xFF):
                try:
                    ch = bytes([b1, b2]).decode(enc)
                except Exception:
                    continue
                if len(ch) == 1 and ("\u3400" <= ch <= "\u9fff" or "\uf900" <= ch <= "\ufaff"):
                    chars.add(ch)
    for enc in ("gbk", "big5"):
        for b1 in range(0x81, 0xFF):
            for b2 in range(0x40, 0xFF):
                try:
                    ch = bytes([b1, b2]).decode(enc)
                except Exception:
                    continue
                if len(ch) == 1 and ("\u3400" <= ch <= "\u9fff" or "\uf900" <= ch <= "\ufaff"):
                    chars.add(ch)
    return "".join(sorted(chars))


common_file = root / 'scripts/i18n/cjk-common.txt'
common_file.write_text(common_cjk_chars(), encoding='utf-8')
print('common CJK charset:', len(common_file.read_text(encoding='utf-8')), 'chars')

# NOTE: the wide fallback faces are NOT embedded any more — the app loads the
# system Noto Sans CJK at runtime (fonts::system_face), which keeps the binary
# small and still covers every GB2312/GBK/Big5 character. cjk-common.txt is kept
# because the font coverage test uses it against that system face.
print('fallback faces are loaded from the system font at runtime')
